#!/usr/bin/env bash
# Brings up the local Stellar quickstart network, builds and deploys the
# contracts, and writes the resulting contract addresses to .env.local.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

RPC_URL="${SOROBAN_RPC_URL:-http://localhost:8000/soroban/rpc}"
NETWORK_PASSPHRASE="Standalone Network ; February 2017"
NETWORK_NAME="local"
IDENTITY="${DEV_IDENTITY:-access-layer-dev}"
ENV_FILE="$ROOT_DIR/.env.local"
WASM_PATH="target/wasm32v1-none/release/creator_keys.wasm"
REFERRAL_WASM_PATH="target/wasm32v1-none/release/referral_contract.wasm"

log() { printf '[dev-up] %s\n' "$*"; }

require() {
  if ! command -v "$1" >/dev/null 2>&1; then
    echo "error: required command '$1' not found. See docs/local-soroban-prerequisites.md" >&2
    exit 1
  fi
}

require docker
require cargo
require stellar
require curl

log "starting Stellar quickstart network"
docker compose up -d stellar-quickstart

log "waiting for Soroban RPC to become healthy"
for _ in $(seq 1 90); do
  if curl -sf -X POST -H 'Content-Type: application/json' \
    -d '{"jsonrpc":"2.0","id":1,"method":"getHealth"}' "$RPC_URL" | grep -q '"healthy"'; then
    break
  fi
  sleep 2
done
if ! curl -sf -X POST -H 'Content-Type: application/json' \
  -d '{"jsonrpc":"2.0","id":1,"method":"getHealth"}' "$RPC_URL" | grep -q '"healthy"'; then
  echo "error: Soroban RPC did not become healthy at $RPC_URL" >&2
  exit 1
fi

log "configuring stellar CLI network and identity"
stellar network add "$NETWORK_NAME" \
  --rpc-url "$RPC_URL" \
  --network-passphrase "$NETWORK_PASSPHRASE" >/dev/null 2>&1 || true

if ! stellar keys address "$IDENTITY" >/dev/null 2>&1; then
  stellar keys generate "$IDENTITY" --network "$NETWORK_NAME" --fund >/dev/null
fi
DEPLOYER="$(stellar keys address "$IDENTITY")"

log "building contracts"
cargo build --release --target wasm32v1-none -p creator-keys -p referral-contract

log "deploying creator-keys contract"
CREATOR_KEYS_ID="$(stellar contract deploy \
  --wasm "$WASM_PATH" \
  --source "$IDENTITY" \
  --network "$NETWORK_NAME")"

log "deploying referral-contract"
REFERRAL_ID="$(stellar contract deploy \
  --wasm "$REFERRAL_WASM_PATH" \
  --source "$IDENTITY" \
  --network "$NETWORK_NAME")"

log "writing addresses to $ENV_FILE"
cat > "$ENV_FILE" <<EOF
# Generated by scripts/dev-up.sh. Do not commit.
SOROBAN_RPC_URL=$RPC_URL
SOROBAN_NETWORK_PASSPHRASE=$NETWORK_PASSPHRASE
SOROBAN_NETWORK=$NETWORK_NAME
DEV_IDENTITY=$IDENTITY
DEV_ADMIN_ADDRESS=$DEPLOYER
CREATOR_KEYS_CONTRACT_ID=$CREATOR_KEYS_ID
REFERRAL_CONTRACT_ID=$REFERRAL_ID
EOF

log "done. contract addresses written to .env.local"
log "next: scripts/seed.sh to populate seed data"
